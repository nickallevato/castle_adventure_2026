export const FONT_W = 5, FONT_H = 8, FONT_ADVANCE = 6;

const glyphs = new Map();
function glyph(ch) {
  if (glyphs.has(ch)) return glyphs.get(ch);
  const def = G[ch] || G["?"];
  const rows = def.split("|");
  const bm = createPlanes(FONT_W, FONT_H, 1);
  bm.mask = new Uint8Array(bm.bpr * FONT_H);
  rows.forEach((r, y) => [...r].forEach((c, x) => { if (c === "#") bm.mask[y * bm.bpr] |= 0x80 >> x; }));
  glyphs.set(ch, bm);
  return bm;
}

export function textWidth(text) { return text.length * FONT_ADVANCE - 1; }

/** Draw text into a planar bitmap in color `color`; optional 1px drop shadow color. */
export function drawText(bm, text, x, y, color, shadow = null) {
  const fillFor = (c) => [...Array(bm.depth).keys()].map((p) => (c >> p) & 1);
  const pass = (ox, oy, c) => {
    const fill = fillFor(c);
    let cx = x + ox;
    for (const ch of text) {
      blit(bm, glyph(ch), cx, y + oy, { fill });
      cx += FONT_ADVANCE;
    }
  };
  if (shadow !== null) pass(1, 1, shadow);
  pass(0, 0, color);
}

/** Pixel rows ('#'/'.') of a glyph, for tests or the HTML chrome. */
export function glyphRows(ch) { return (G[ch] || G["?"]).split("|"); }
